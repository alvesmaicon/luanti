HEIGHTS = [3, 6, 9, 12]
STALKS = [[5, 10], [3, 7, 12], [2, 6, 9, 13], [2, 5, 8, 11, 14]]


def crop(leaf, root, stage):
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))

    def put(x, y, c):
        if 0 <= x < 16 and 0 <= y < 16:
            img.putpixel((x, y), hexc(c) + (255,))

    h = HEIGHTS[stage]
    for i, x in enumerate(STALKS[stage]):
        top = 16 - h + (i % 2) * 2
        lean = -1 if i % 2 else 1
        for y in range(top, 16):
            put(x, y, leaf["G"])
        # a leaf every other row, out and up to one side then the other
        for n, y in enumerate(range(top + 1, 15, 2)):
            side = lean if n % 2 else -lean
            put(x + side, y, leaf["g"])
            put(x + 2 * side, y - 1, leaf["l"] if y < top + 4 else leaf["g"])
        put(x, top, leaf["l"])
        put(x + lean, top - 1, leaf["l"])
        if stage == 3 and i % 2 == 0:
            put(x, 14, root["o"])
            put(x, 15, root["o"])
            put(x + 1, 15, root["O"])
    return img


def ribbed(base, dark, light, top):
    img = Image.new("RGBA", (16, 16))
    for y in range(16):
        for x in range(16):
            if top:
                import math
                a = (math.atan2(y - 7.5, x - 7.5) + math.pi) / (2 * math.pi) * 8
                r = math.hypot(x - 7.5, y - 7.5)
                c = dark if abs(a - round(a)) < 0.12 and r > 2 else (light if (a % 1) < 0.35 and r < 6 else base)
            else:
                c = dark if x % 5 == 0 else (light if x % 5 == 2 and 2 < y < 13 else base)
            img.putpixel((x, y), hexc(c) + (255,))
    return img


